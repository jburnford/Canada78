#!/usr/bin/env python3
"""Render the Phase 1 validation-gate review packet as Markdown.

Samples segments from the gate volumes (letters era early/late, transitional,
thematic; BC + prairie regions), shows their text with inline mention
markup, and lists the registry review queues. The historian marks each
sampled item; findings feed curation files, not code edits to outputs.

Output: docs/VALIDATION_GATE_PACKET.md
"""
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DIA_MD = Path.home() / "DeptIndianAffairs/markdown"
GATE_TAGS = ["dia_ar_1885", "dia_ar_1900", "dia_ar_1913", "dia_ar_1925"]
MAX_CHARS = 2200


def body_of(tag):
    raw = (DIA_MD / f"{tag}.md").read_text(encoding="utf-8", errors="replace")
    m = re.match(r"^---\n.*?\n---\n", raw, re.S)
    return raw[m.end():] if m else raw


def markup(text, anns):
    """Insert [surface]{type:id:conf} markers, right-to-left."""
    out = text
    for a in sorted(anns, key=lambda a: -a["char_start"]):
        if a["char_end"] > len(out):
            continue
        tag = f"{{{a['entity_type']}:{a['entity_id']}:{a['confidence']}}}"
        out = out[: a["char_start"]] + "[" + out[a["char_start"]: a["char_end"]] + "]" + tag + out[a["char_end"]:]
    return out


def main():
    segs = pd.read_parquet(ROOT / "registries/documents/dia_segments.parquet")
    ann = pd.read_parquet(ROOT / "registries/annotations/mentions_dia_sample.parquet")
    res = pd.read_parquet(ROOT / "registries/annotations/mention_residuals_dia_sample.parquet")

    lines = ["# Phase 1 Validation Gate — Review Packet", "",
             "_Generated by `build/make_gate_packet.py`. Mark each sampled item "
             "OK / FIX (with note). Findings go to `curation/` files; nothing "
             "is hand-edited in generated outputs._", ""]

    lines += ["## A. Linking statistics (gate volumes)", ""]
    lines.append(f"Mentions: {len(ann)} | residuals for Tier 2: {len(res)}")
    lines.append("")
    lines.append("| type | high | medium | low |")
    lines.append("|---|---|---|---|")
    ct = ann.groupby(["entity_type", "confidence"]).size().unstack(fill_value=0)
    for t, row in ct.iterrows():
        lines.append(f"| {t} | {row.get('high', 0)} | {row.get('medium', 0)} | {row.get('low', 0)} |")
    lines.append("")
    lines.append(f"Region-mismatch (low, kept for measurement): "
                 f"{ann.note.fillna('').str.contains('region').sum()}")
    lines.append("")

    lines += ["## B. Sampled segments with mention markup", "",
              "Marker format: `[surface]{type:entity_id:confidence}`. Check: "
              "(1) segment boundaries sensible? (2) heading/province right? "
              "(3) each marked mention correct entity + type? (4) obvious misses?",
              ""]
    rng = 11
    for tag in GATE_TAGS:
        body = body_of(tag)
        s = segs[segs.tag == tag]
        picks = []
        for kind in ["agency_letter", "thematic_section", "tabular_statement"]:
            pool = s[s.kind == kind]
            if len(pool):
                picks.append(pool.sample(min(2, len(pool)), random_state=rng))
        for seg in pd.concat(picks).itertuples():
            text = body[seg.char_start: seg.char_end]
            a = ann[(ann.tag == tag) & (ann.segment_id == seg.segment_id)]
            a = a[a.char_end <= MAX_CHARS].to_dict("records")
            shown = markup(text[:MAX_CHARS], a)
            lines.append(f"### {tag} · `{seg.segment_id}` · {seg.kind}")
            lines.append(f"heading: **{seg.heading}** · province hint: {seg.province} · "
                         f"pp. {seg.page_start}–{seg.page_end} · {len(a)} mentions shown"
                         f"{' (truncated)' if len(text) > MAX_CHARS else ''}")
            lines.append("")
            lines.append("```")
            lines.append(shown.strip())
            lines.append("```")
            lines.append("- [ ] boundaries  - [ ] heading/province  - [ ] mentions  - [ ] misses")
            lines.append("")

    lines += ["## C. Residual sample (for Tier 2 design)", ""]
    for r in res.sample(min(12, len(res)), random_state=rng).itertuples():
        lines.append(f"- `{r.tag}` {r.surface!r} → {r.candidates} {('· ' + r.note) if isinstance(r.note, str) else ''}")
    lines.append("")

    lines += ["## D. Registry review queues", "",
              "- `registries/crosswalks/band_wikidata_review.csv` — 73 band grounding calls (medium/low/none)",
              "- `registries/crosswalks/agency_chain_event_candidates.csv` — 584 auto-suggested chain events (token-sharing, adjacent spans); confirmed ones live in `curation/agency_chain_events.csv`",
              "- `registries/entities/reserves.parquet` — 90 reserves with null division (two Ontario pages + eastern county sections)",
              "- `docs/RESERVES_1902_EXTRACTION.md` — 745 medium-confidence Schedule rows with preserved OCR artifacts",
              "", "## E. Decisions this gate should settle", "",
              "1. Confidence threshold for publishing a mention on a wiki page (proposal: high + medium; low shown only in an 'unverified mentions' fold).",
              "2. Whether bare-name Tier 0 matches inside tables are worth keeping at all.",
              "3. Province-hint reliability: fix the segmenter's dateline parsing, or rely on agency-context only?",
              "4. Person entities: mint from signatures where LINCS has no match (145 signatures in the sample)?",
              ""]
    (ROOT / "docs/VALIDATION_GATE_PACKET.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote docs/VALIDATION_GATE_PACKET.md", len("\n".join(lines)), "chars")


if __name__ == "__main__":
    sys.exit(main())
